    md = [f"# {unidad.upper()} · Ejercicios adicionales", "", "50 ejercicios distintos de los ejercicios originales de practicar y entregar.", "", '!!! note "Organización"', "    **1–20:** básicos · **21–40:** intermedios · **41–50:** repaso.", ""]
    for numero, (titulo, enunciado) in enumerate(ejercicios, 1):
        texto = f'"""\nEjercicio {numero:02d}: {titulo}\n\n{enunciado}\n"""\n\n# Escribe tu solución a partir de aquí:\n'
